var UNLOCK_RATIO = .8;
function regionIndex(id) {
	return REGION_ORDER.indexOf(id);
}
function highestUnlockedRegion(mastery) {
	let unlocked = "lage-landen";
	for (let i = 0; i < REGION_ORDER.length - 1; i++) {
		const region = REGION_ORDER[i];
		const members = COUNTRIES.filter((c) => c.region === region);
		const ready = members.filter((c) => (mastery[c.iso] ?? 0) >= 2).length;
		if (members.length > 0 && ready / members.length >= .8) unlocked = REGION_ORDER[i + 1];
		else break;
	}
	return unlocked;
}
function playableCountries(mastery) {
	const cap = regionIndex(highestUnlockedRegion(mastery));
	return COUNTRIES.filter((c) => regionIndex(c.region) <= cap);
}
function learnerStage(mastery) {
	const mastered = Object.values(mastery).filter((v) => v >= 3).length;
	if (mastered >= 16) return "atlas";
	if (mastered >= 8) return "courier";
	if (mastered >= 3) return "apprentice";
	return "novice";
}
